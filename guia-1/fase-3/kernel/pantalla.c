void pantalla_iniciar(const struct mb2_tag_framebuffer *fb)
{
    base        = (volatile uint8_t *)(uintptr_t)fb->direccion;
    ancho       = fb->ancho;
    alto        = fb->alto;
    pitch       = fb->pitch;
    bytes_pixel = fb->bpp / 8;
    rojo_pos    = fb->rojo_pos;   rojo_bits  = fb->rojo_bits;
    verde_pos   = fb->verde_pos;  verde_bits = fb->verde_bits;
    azul_pos    = fb->azul_pos;   azul_bits  = fb->azul_bits;
}

uint32_t pantalla_ancho(void) { return ancho; }
uint32_t pantalla_alto(void)  { return alto; }

uint32_t pantalla_color(uint8_t r, uint8_t g, uint8_t b)
{
    return ((uint32_t)(r >> (8 - rojo_bits))  << rojo_pos)
         | ((uint32_t)(g >> (8 - verde_bits)) << verde_pos)
         | ((uint32_t)(b >> (8 - azul_bits))  << azul_pos);
}

void pantalla_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= ancho || y >= alto)
        return;                 /* nunca escribir fuera del framebuffer */
    volatile uint8_t *p = base + y * pitch + x * bytes_pixel;
    if (bytes_pixel == 4) {
        *(volatile uint32_t *)p = color;
    } else {                    /* 24 bpp */
        p[0] = (uint8_t)color;
        p[1] = (uint8_t)(color >> 8);
        p[2] = (uint8_t)(color >> 16);
    }
}

void pantalla_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t j = y; j < y + h && j < alto; j++)
        for (uint32_t i = x; i < x + w && i < ancho; i++)
            pantalla_pixel(i, j, color);
}

void pantalla_texto(uint32_t x, uint32_t y, const char *s, uint32_t escala, uint32_t color)
{
    for (; *s; s++, x += 6 * escala) {
        char c = *s;
        if (c >= 'a' && c <= 'z')
            c = (char)(c - 'a' + 'A');
        if (c < 32 || c >= 96)
            continue;
        const uint8_t *g = fuente[c - 32];
        for (uint32_t fila = 0; fila < 7; fila++)
            for (uint32_t col = 0; col < 5; col++)
                if (g[fila] & (0x10 >> col))
                    pantalla_rect(x + col * escala, y + fila * escala, escala, escala, color);
    }
}
